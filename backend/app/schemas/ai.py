from pydantic import BaseModel, Field
from typing import List, Optional, Dict, Any


class AIScoreUpdateRequest(BaseModel):
    aiScore: int = Field(..., ge=0, le=100, description="Lead propensity score between 0 and 100")
    conversionProbability: float = Field(..., ge=0.0, le=1.0, description="Predicted close probability (0.0 - 1.0)")
    keyFactors: Optional[List[str]] = Field([], description="Feature importance drivers identified by ML model")
    modelVersion: Optional[str] = "belvo-propensity-v1.2"


class AISummaryUpdateRequest(BaseModel):
    summary: str = Field(..., min_length=5, description="Executive prospect summary generated by NLP model")
    sentiment: Optional[str] = Field("Positive", description="Overall prospect sentiment")
    buyingIntent: Optional[str] = Field("High", description="High / Medium / Low")
    modelVersion: Optional[str] = "belvo-nlp-summary-v1.0"


class AILeadInsightsResponse(BaseModel):
    leadId: str
    company: str
    fullName: str
    aiScore: int
    conversionProbability: float
    aiSummary: str
    keyFactors: List[str]
    recommendedStage: str
    nextBestActions: List[str]


class AIMessageDraftRequest(BaseModel):
    channel: str = Field("Email", description="'Email', 'WhatsApp', or 'LinkedIn'")
    tone: Optional[str] = Field("Professional", description="'Professional', 'Casual', or 'Direct'")
    objective: Optional[str] = Field("Follow-up on product proposal", description="Goal of communication")


class AIMessageDraftResponse(BaseModel):
    leadId: str
    channel: str
    subject: Optional[str] = None
    bodyDraft: str
    suggestedSendTime: str
    confidence: float


class AIDailyManagerItem(BaseModel):
    urgency: str  # 'Critical', 'High', 'Medium'
    title: str
    leadId: str
    company: str
    action: str
    reason: str


class AIDailyManagerResponse(BaseModel):
    date: str
    salesSpecialist: str
    totalFocusLeads: int
    overdueAlerts: List[AIDailyManagerItem]
    topOpportunities: List[AIDailyManagerItem]
    stalledDeals: List[AIDailyManagerItem]
    dailySummary: str


class AIDuplicateCandidate(BaseModel):
    existingLeadId: str
    company: str
    name: str
    matchType: str
    confidenceScore: float
    similarityDetails: Dict[str, float]


class AIDuplicateAnalysisResponse(BaseModel):
    hasPotentialDuplicate: bool
    candidates: List[AIDuplicateCandidate]
